const esc = s => String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
const block = (e, open) => `<details class="clv"${open ? ' open' : ''}><summary><b>${esc(e.v)}${e.n ? ` · ${esc(e.n)}` : ''}</b><small>${esc(e.d)}</small></summary><ul>${e.items.map(t => `<li>${esc(t)}</li>`).join('')}</ul></details>`;
export function changelogHtml() {
  return `<h2>更新日志</h2><p class="hint">寒烬北行 ${VERSION_NAME}。点一个版本展开看它加了什么。</p>
<div class="clog">${CHANGELOG.map((e, i) => block(e, i < 2)).join('')}</div>`;
}
